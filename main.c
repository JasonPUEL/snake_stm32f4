{Maillon* L_Maillon = malloc(sizeof(Maillon));
L_Maillon->X=X;
L_Maillon->Y=Y;
L_Maillon->Suivant = Debut_Liste;
Debut_Liste=L_Maillon;}

void Effacer_Liste()//RESET
{Maillon* L_Maillon;
while(Debut_Liste){
	L_Maillon=Debut_Liste->Suivant;
	//calloc(Debut_Liste);
	free(Debut_Liste);
	Debut_Liste = L_Maillon;}
}
