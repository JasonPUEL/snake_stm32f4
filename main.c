//==============================================
void Init_Serpent(){
	Ajoute_Valeur(LCD_Limite_Max/2,LCD_Limite_Max/2);
	Direction.x=0;
	Direction.y=0;
}

void Afficher(uint8_t DIR_X,uint8_t DIR_Y){
	if (DIR_X != 0 || DIR_Y != 0){
		BSP_LCD_Clear(LCD_COLOR_BLACK);

		Maillon* L_Maillon=Debut_Liste;
		while(L_Maillon){
			BSP_LCD_SetTextColor(LCD_COLOR_WHITE);
			BSP_LCD_FillRect(L_Maillon->X,L_Maillon->Y,Longueur_cube,Longueur_cube);
			BSP_LCD_SetTextColor(LCD_COLOR_RED);
			BSP_LCD_DrawRect(L_Maillon->X,L_Maillon->Y,Longueur_cube,Longueur_cube);
			L_Maillon=L_Maillon->Suivant;
		}
		BSP_LCD_SetTextColor(LCD_COLOR_RED);
		BSP_LCD_FillCircle(Pomme.x+Longueur_cube/2,Pomme.y+Longueur_cube/2,Longueur_cube/2);
	}
}

void Gestion_Bord(){
	Maillon* L_Maillon=Debut_Liste;
	if (Debut_Liste-> X>= LCD_Limite_Max || Debut_Liste->X < LCD_Limite_Min ){GameOver();}
	if (Debut_Liste->Y >= LCD_Limite_Max || Debut_Liste->Y < LCD_Limite_Min ){GameOver();}
	while(L_Maillon->Suivant){
		L_Maillon=L_Maillon->Suivant;
		if(Debut_Liste->X==L_Maillon->X && Debut_Liste->Y==L_Maillon->Y){GameOver();}
	}
}

void Deplacement(uint8_t DIR_X,uint8_t DIR_Y){
	if (DIR_X != 0 || DIR_Y != 0){
		Maillon* L_Maillon=Debut_Liste;

		uint8_t A = L_Maillon->X;
		uint8_t B = L_Maillon->Y;
		uint8_t C;
		uint8_t D;
		L_Maillon->X=L_Maillon->X + DIR_X;
		L_Maillon->Y=L_Maillon->Y + DIR_Y;
		L_Maillon=L_Maillon->Suivant;
		while(L_Maillon){
			C=L_Maillon->X;
			D=L_Maillon->Y;
			L_Maillon->X=A;
			L_Maillon->Y=B;
			L_Maillon=L_Maillon->Suivant;
			A=C;
			B=D;
		}
	}
}

void GameOver(){
	char string[]="GAME OVER";
	BSP_LCD_Clear(LCD_COLOR_RED);
	//BSP_LCD_SetBackColor(LCD_COLOR_RED)
	BSP_LCD_SetTextColor(LCD_COLOR_BLACK);
	BSP_LCD_DisplayStringAt(LCD_Limite_Max,LCD_Limite_Max/2, string,CENTER_MODE);
	Effacer_Liste();
	Init_Serpent();
	Add_Pomme();
}

void Add_Pomme(){
	Maillon* L_Maillon;
	uint8_t k = 0;
	while(k != 1){
		L_Maillon=Debut_Liste;
		Pomme.x = (rand() % (24))*10;
		Pomme.y = (rand() % (24))*10;
		while(L_Maillon){
			if(L_Maillon->X == Pomme.x && L_Maillon->Y == Pomme.y){k=0;}
			else k=1;
			L_Maillon=L_Maillon->Suivant;
		}
	}
}

void Gestion_Pomme(){
	if(Debut_Liste->X==Pomme.x && Debut_Liste->Y==Pomme.y){
		Ajoute_Valeur(Debut_Liste->X+Direction.x,Debut_Liste->Y+Direction.y);
		Add_Pomme();
	}
}
